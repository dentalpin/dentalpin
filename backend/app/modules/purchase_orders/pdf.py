"""Purchase order PDF generation.

Mirrors `billing/pdf.py`'s `InvoicePDFService` shape exactly — same
`_html_to_pdf` WeasyPrint pattern, same currency-formatting helper —
but without any of the fiscal/compliance machinery (no QR codes, no
legal notices, no credit-note handling). This is an internal
procurement document, not a fiscal invoice.

This PDF is generated on demand for in-app preview/download only. It
is NOT attached to the "send to supplier" email — see
`service.py`'s `_send_email` docstring for why (matches how
invoice_sent/budget_sent already behave in this codebase: neither
attaches a PDF either).
"""

