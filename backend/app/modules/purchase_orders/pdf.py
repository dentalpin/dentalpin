class PurchaseOrderPDFService:
    """Self-contained WeasyPrint PDF for a purchase order."""

    @staticmethod
    async def generate_pdf(response: dict, clinic: Clinic, locale: str = "es") -> bytes:
        html = PurchaseOrderPDFService._generate_html(response, clinic, locale)
        return await asyncio.to_thread(PurchaseOrderPDFService._html_to_pdf, html)

    @staticmethod
    def _generate_html(response: dict, clinic: Clinic, locale: str) -> str:
        labels = _LABELS.get(locale, _LABELS["es"])
        status_label = labels["status_label"].get(response["status"], response["status"])
        currency = clinic.currency if clinic else "EUR"
        money_locale = "es_ES" if locale == "es" else "en_US"

        def money(amount: Decimal) -> str:
            return _fmt_currency(amount, currency, locale=money_locale)

        rows = ""
        grand_total = Decimal("0")
        for idx, line in enumerate(response["lines"], 1):
            line_total = (line["unit_price"] or Decimal("0")) * line["quantity_ordered"]
            grand_total += line_total
            rows += f"""
                <tr>
                    <td class="number">{idx}</td>
                    <td>{escape(line["item_name"])}</td>
                    <td class="qty">{line["quantity_ordered"]}</td>
                    <td class="qty">{line["quantity_received"]}</td>
                    <td class="price">{money(line["unit_price"] or Decimal("0"))}</td>
                    <td class="price">{money(line_total)}</td>
                </tr>
            """

        expected = (
            response["expected_date"].strftime("%d/%m/%Y") if response["expected_date"] else "—"
        )
        created = response["created_at"].strftime("%d/%m/%Y")

        watermark = ""
        if response["status"] == "draft":
            watermark = f'<div class="watermark">{labels["draft"]}</div>'

        note_block = (
            f'<div class="notes-section"><div class="section-title">{labels["notes"]}</div>'
            f'<div class="notes-content">{escape(response["notes"])}</div></div>'
            if response.get("notes")
            else ""
        )

        return f"""<!DOCTYPE html>
        <html lang="{locale}">
        <head>
        <meta charset="UTF-8">
        <style>
            * {{ margin: 0; padding: 0; box-sizing: border-box; }}
            body {{
                font-family: 'Helvetica Neue', Arial, sans-serif;
                font-size: 11pt; line-height: 1.4; color: #333; padding: 20mm;
            }}
            .watermark {{
                position: fixed; top: 50%; left: 50%;
                transform: translate(-50%, -50%) rotate(-45deg);
                font-size: 120px; color: rgba(200, 200, 200, 0.3); z-index: 1000;
            }}
            .header {{
                display: flex; justify-content: space-between;
                margin-bottom: 30px; padding-bottom: 20px;
                border-bottom: 2px solid #2563eb;
            }}
            .clinic-name {{ font-size: 18pt; font-weight: bold; color: #1e40af; margin-bottom: 5px; }}
            .clinic-details {{ font-size: 9pt; color: #666; }}
            .po-info {{ text-align: right; }}
            .po-number {{ font-size: 14pt; font-weight: bold; color: #1e40af; }}
            .po-meta {{ font-size: 9pt; color: #666; margin-top: 5px; }}
            .status-badge {{
                display: inline-block; padding: 3px 10px; border-radius: 12px;
                font-size: 9pt; font-weight: bold; text-transform: uppercase; margin-top: 8px;
            }}
            .status-draft {{ background: #e5e7eb; color: #374151; }}
            .status-sent {{ background: #dbeafe; color: #1e40af; }}
            .status-confirmed {{ background: #fef3c7; color: #92400e; }}
            .status-received {{ background: #d1fae5; color: #065f46; }}
            .status-cancelled {{ background: #fee2e2; color: #991b1b; }}
            .section {{ margin-bottom: 25px; }}
            .section-title {{
                font-size: 11pt; font-weight: bold; color: #1e40af;
                margin-bottom: 10px; padding-bottom: 5px; border-bottom: 1px solid #e5e7eb;
            }}
            table {{ width: 100%; border-collapse: collapse; }}
            th {{
                background: #f3f4f6; padding: 10px 8px; text-align: left;
                font-size: 9pt; font-weight: 600; color: #374151;
                border-bottom: 2px solid #e5e7eb;
            }}
            td {{ padding: 10px 8px; border-bottom: 1px solid #e5e7eb; vertical-align: top; }}
            .number {{ width: 30px; text-align: center; }}
            .qty {{ width: 70px; text-align: center; }}
            .price {{ width: 110px; text-align: right; }}
            .totals {{ float: right; width: 300px; margin-top: 20px; }}
            .totals td {{ border-bottom: none; padding: 6px 8px; }}
            .totals .label {{ text-align: left; color: #666; }}
            .totals .value {{ text-align: right; font-weight: 500; }}
            .totals .grand-total {{ font-size: 13pt; font-weight: bold; color: #1e40af; }}
            .notes-section {{ clear: both; padding-top: 20px; margin-top: 20px; }}
            .notes-content {{
                background: #f9fafb; padding: 15px; border-radius: 8px;
                font-size: 10pt; color: #4b5563;
            }}
            .supplier {{ margin-bottom: 15px; }}
            .info-label {{ font-size: 9pt; color: #666; margin-bottom: 2px; }}
            .info-value {{ font-weight: 500; }}
        </style>
        </head>
        <body>
            {watermark}
            <div class="header">
                <div class="clinic-info">
                    <div class="clinic-name">{escape(clinic.name) if clinic else "Dental Clinic"}</div>
                    <div class="clinic-details">{escape(clinic.phone or "")}</div>
                </div>
                <div class="po-info">
                    <div class="po-number">{labels["po"]} {str(response["id"])[:8].upper()}</div>
                    <div class="po-meta">
                        {labels["created_at"]}: {created}
                    </div>
                    <span class="status-badge status-{response["status"]}">{status_label}</span>
                </div>
            </div>

            <div class="section">
                <div class="section-title">{labels["supplier"]}</div>
                <div class="supplier">
                    <div class="info-value">{escape(response["supplier_name"])}</div>
                    <div class="info-label">{labels["expected_date"]}</div>
                    <div class="info-value">{expected}</div>
                </div>
            </div>

            <div class="section">
                <div class="section-title">{labels["item"]}s</div>
                <table>
                    <thead>
                        <tr>
                            <th class="number">#</th>
                            <th>{labels["item"]}</th>
                            <th class="qty">{labels["qty_ordered"]}</th>
                            <th class="qty">{labels["qty_received"]}</th>
                            <th class="price">{labels["unit_price"]}</th>
                            <th class="price">{labels["line_total"]}</th>
                        </tr>
                    </thead>
                    <tbody>{rows}</tbody>
                </table>
                <div class="totals">
                    <table>
                        <tr><td class="label">{labels["total"]}:</td><td class="value grand-total">{money(grand_total)}</td></tr>
                    </table>
                </div>
            </div>

            {note_block}

            <div style="clear: both; padding-top: 30px;"></div>
            <div style="font-size: 8pt; color: #9ca3af; text-align: center; border-top: 1px solid #e5e7eb; padding-top: 10px;">
                {labels["generated_by"]} DentalPin | {datetime.now().strftime("%d/%m/%Y %H:%M")}
            </div>
        </body>
        </html>"""

    @staticmethod
    def _html_to_pdf(html_content: str) -> bytes:
        try:
            from weasyprint import HTML

            pdf_buffer = BytesIO()
            HTML(string=html_content).write_pdf(pdf_buffer)
            return pdf_buffer.getvalue()
        except ImportError:
            return html_content.encode("utf-8")
